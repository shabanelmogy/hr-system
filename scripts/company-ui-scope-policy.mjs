import fs from 'node:fs';

export const companyUiScopePolicy = JSON.parse(fs.readFileSync(new URL('./company-ui-scope-policy.json', import.meta.url), 'utf8'));

function matches(key, prefix) {
  return prefix.endsWith('*')
    ? key.startsWith(prefix.slice(0, -1))
    : key === prefix || key.startsWith(prefix + '.') || key.startsWith(prefix + '_');
}

export function companyUiTextScope(client, namespace, key) {
  const policy = companyUiScopePolicy;
  const sourceScope = client === 'web' && Object.hasOwn(policy.web.namespaces, namespace) ? policy.web.namespaces[namespace]
    : client === 'mobile' && namespace === policy.mobile.namespace ? 'mixed' : null;
  if (!sourceScope) return null;
  if (sourceScope === 'system' || [...policy.systemPrefixes, ...policy[client].systemPrefixes].some(prefix => matches(key, prefix))) return 'system';
  if (client === 'web') return sourceScope;
  const root = key.split('.')[0];
  if (policy.mobile.sharedRoots.includes(root)) return 'shared';
  if (policy.mobile.companyRoots.includes(root)) return 'company';
  return null;
}

export function generateClientScopePolicy(client) {
  const policy = companyUiScopePolicy;
  const sources = client === 'web' ? policy.web.namespaces : { [policy.mobile.namespace]: 'mixed' };
  return `// Generated by scripts/export-company-ui-catalog.mjs from company-ui-scope-policy.json. Do not edit.
type UiTextScope = "company" | "shared" | "system";
const sourceScopes: Readonly<Record<string, string>> = ${JSON.stringify(sources)};
const systemPrefixes: readonly string[] = ${JSON.stringify([...policy.systemPrefixes, ...policy[client].systemPrefixes])};
${client === 'mobile' ? `const sharedRoots: readonly string[] = ${JSON.stringify(policy.mobile.sharedRoots)};
const companyRoots: readonly string[] = ${JSON.stringify(policy.mobile.companyRoots)};` : ''}
function matches(key: string, prefix: string): boolean {
  return prefix.endsWith("*") ? key.startsWith(prefix.slice(0, -1))
    : key === prefix || key.startsWith(prefix + ".") || key.startsWith(prefix + "_");
}
export function companyUiTextScope(namespace: string, key: string): UiTextScope | null {
  const scope = Object.hasOwn(sourceScopes, namespace) ? sourceScopes[namespace] : null;
  if (!scope) return null;
  if (scope === "system" || systemPrefixes.some(prefix => matches(key, prefix))) return "system";
  ${client === 'mobile' ? `const root = key.split(".")[0];
  return sharedRoots.includes(root) ? "shared" : companyRoots.includes(root) ? "company" : null;` : 'return scope === "company" || scope === "shared" ? scope : null;'}
}
export function isCompanyUiText(namespace: string, key: string): boolean {
  const scope = companyUiTextScope(namespace, key);
  return scope === "company" || scope === "shared";
}
export function isCompanyUiSource(namespace: string): boolean {
  return Object.hasOwn(sourceScopes, namespace) && sourceScopes[namespace] !== "system";
}
`;
}
