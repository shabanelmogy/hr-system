#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { companyUiTextScope, generateClientScopePolicy } from './company-ui-scope-policy.mjs';

import { systemUiPermissions, generateSystemUiPolicy } from './system-ui-access-policy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const ts = require(path.join(root, 'web-next/node_modules/typescript'));
const forbidden = new Set(['__proto__', 'prototype', 'constructor']);
function flatten(value, prefix = '', output = {}) {
  if (typeof value === 'string') { output[prefix] = value; return output; }
  if (!value || typeof value !== 'object' || Array.isArray(value)) return output;
  for (const key of Object.keys(value).sort()) {
    if (forbidden.has(key)) throw new Error('Unsafe resource key: ' + key);
    flatten(value[key], prefix ? prefix + '.' + key : key, output);
  }
  return output;
}
const readJson = (relative) => JSON.parse(fs.readFileSync(path.join(root, relative), 'utf8'));
const sources = [];
function addSource(client, namespace, en, ar) {
  const english = flatten(en), arabic = flatten(ar);
  const keys = [...new Set([...Object.keys(english), ...Object.keys(arabic)])].sort();
  sources.push({ id: client + ':' + namespace, client, namespace,
    entries: keys.map((key) => {
      const scope = companyUiTextScope(client, namespace, key);
      if (!scope) throw new Error('UI text requires explicit scope classification: ' + client + ':' + namespace + ':' + key);
      return { key, en: english[key] ?? null, ar: arabic[key] ?? null, scope, systemPermissions: systemUiPermissions(client, namespace, key) };
    }) });
}
const staticRoot = 'web-next/src/locales/resources';
for (const directory of fs.readdirSync(path.join(root, staticRoot)).sort()) {
  if (!fs.existsSync(path.join(root, staticRoot, directory, 'en.json'))) continue;
  addSource('web', directory, readJson(staticRoot + '/' + directory + '/en.json'), readJson(staticRoot + '/' + directory + '/ar.json'));
}
for (const module of ['accounting', 'hr']) {
  addSource('web', 'module-' + module,
    readJson('web-next/src/modules/' + module + '/locales/en.json'),
    readJson('web-next/src/modules/' + module + '/locales/ar.json'));
}
// Evaluate only the repository's pure resource composition files during generation.
// The API consumes the embedded JSON; Node/TypeScript are not API runtime dependencies.
const originalTsExtension = require.extensions['.ts'];
require.extensions['.ts'] = (loadedModule, filename) => {
  const resourcesRoot = path.join(root, 'mobile-react/src/core/localization/translations') + path.sep;
  if (!path.resolve(filename).startsWith(resourcesRoot)) throw new Error('Unexpected translation import: ' + filename);
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    fileName: filename,
  }).outputText;
  loadedModule._compile(compiled, filename);
};
try {
  const english = require(path.join(root, 'mobile-react/src/core/localization/translations/en.ts')).en;
  const arabic = require(path.join(root, 'mobile-react/src/core/localization/translations/ar.ts')).ar;
  addSource('mobile', 'translation', english, arabic);
} finally {
  if (originalTsExtension) require.extensions['.ts'] = originalTsExtension;
  else delete require.extensions['.ts'];
}
sources.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
const versions = Object.fromEntries(['web', 'mobile'].map((client) => [
  client, createHash('sha256').update(JSON.stringify(sources.filter((source) => source.client === client))).digest('hex'),
]));
const artifact = { schemaVersion: 3, versions, sources };
const outputs = new Map([
  ['api/Modules/Platform/ErpSystem.Modules.Platform.Infrastructure/Features/CompanyLocalization/company-ui-catalog.json', JSON.stringify(artifact, null, 2) + '\n'],
  ['web-next/src/config/company-ui-catalog-version.ts', '// Generated by scripts/export-company-ui-catalog.mjs. Do not edit.\nexport const companyUiCatalogVersion = "' + versions.web + '";\n'],
  ['mobile-react/src/core/localization/company-ui-catalog-version.ts', '// Generated by scripts/export-company-ui-catalog.mjs. Do not edit.\nexport const companyUiCatalogVersion = "' + versions.mobile + '";\n'],
  ['web-next/src/config/company-ui-text-scope.ts', generateClientScopePolicy('web')],
  ['mobile-react/src/core/localization/company-ui-text-scope.ts', generateClientScopePolicy('mobile')],
]);
outputs.set('web-next/src/config/system-ui-text-access.ts', generateSystemUiPolicy('web'));
outputs.set('mobile-react/src/core/localization/system-ui-text-access.ts', generateSystemUiPolicy('mobile'));
const check = process.argv.includes('--check');
let stale = false;
for (const [relative, content] of outputs) {
  const absolute = path.join(root, relative);
  if (check) {
    if (!fs.existsSync(absolute) || fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n') !== content) {
      process.stderr.write('Stale company UI catalog artifact: ' + relative + '\n'); stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, content, 'utf8');
  }
}
if (stale) process.exitCode = 1;
else process.stdout.write('Company UI catalog ' + (check ? 'checked' : 'generated') + ': ' + sources.length + ' sources, '
  + sources.reduce((sum, source) => sum + source.entries.length, 0) + ' keys.\n');
