import fs from 'node:fs';
export const systemUiAccessPolicy = JSON.parse(fs.readFileSync(new URL('./system-ui-access-policy.json', import.meta.url), 'utf8'));
export function systemUiPermissions(client, namespace, key) {
  const rule = systemUiAccessPolicy.find(item => item.client === client && item.namespace === namespace && (!item.prefix || key === item.prefix || key.startsWith(item.prefix + '.')));
  return rule ? rule.permissions : null;
}
export function generateSystemUiPolicy(client) {
  const rules = systemUiAccessPolicy.filter(item => item.client === client).map(({namespace,prefix,permissions}) => ({namespace,prefix,permissions}));
  return `// Generated by scripts/export-company-ui-catalog.mjs. Do not edit.
const rules = ${JSON.stringify(rules)};
export function isAuthorizedSystemUiText(namespace: string, key: string, permissions: readonly string[]): boolean {
  if (key.split('.').some(segment => ['__proto__', 'constructor', 'prototype'].includes(segment))) return false;
  const rule = rules.find(item => item.namespace === namespace && (!item.prefix || key === item.prefix || key.startsWith(item.prefix + '.')));
  return Boolean(rule && rule.permissions.every(permission => permissions.includes(permission)));
}
`;
}
